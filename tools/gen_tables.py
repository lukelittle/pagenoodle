#!/usr/bin/env python3
"""Generate engine/src/tables.c: standard encodings, base-14 widths, glyph-name→Unicode.

Sources (permissively licensed metric data):
  * Adobe Core14 AFM widths & encodings as packaged in ReportLab (BSD)
  * Adobe Glyph List as packaged in fontTools (BSD / Apache-2.0)
Run: python3 tools/gen_tables.py > engine/src/tables.c
"""
from reportlab.pdfbase import _fontdata as fd
from fontTools import agl

FONTS = ['Courier', 'Courier-Bold', 'Courier-Oblique', 'Courier-BoldOblique',
         'Helvetica', 'Helvetica-Bold', 'Helvetica-Oblique', 'Helvetica-BoldOblique',
         'Times-Roman', 'Times-Bold', 'Times-Italic', 'Times-BoldItalic',
         'Symbol', 'ZapfDingbats']
ENCS = [('win', fd.WinAnsiEncoding), ('mac', fd.MacRomanEncoding), ('std', fd.StandardEncoding),
        ('pdfdoc', fd.PDFDocEncoding), ('symbol', fd.SymbolEncoding), ('zapf', fd.ZapfDingbatsEncoding)]

names = set()
for _, enc in ENCS:
    names.update(n for n in enc if n)
for f in FONTS:
    names.update(fd.widthsByFontGlyph[f].keys())
names = sorted(names)
idx = {n: i for i, n in enumerate(names)}

def uni(n):
    if n in agl.AGL2UV:
        return agl.AGL2UV[n]
    if n.startswith('uni') and len(n) == 7:
        try: return int(n[3:], 16)
        except ValueError: pass
    if n.startswith('a') and n[1:].isdigit():  # ZapfDingbats names
        return 0
    return 0

out = []
w = out.append
w('/* Generated by tools/gen_tables.py — do not edit. */')
w('#include "pn_tables.h"')
w(f'const int pn_glyph_count = {len(names)};')
w('const char *const pn_glyph_names[] = {')
w(',\n'.join(f'  "{n}"' for n in names))
w('};')
w('const unsigned int pn_glyph_unicode[] = {')
w(','.join(str(uni(n)) for n in names))
w('};')
for key, enc in ENCS:
    w(f'const unsigned short pn_enc_{key}[256] = {{')
    w(','.join(str(idx[n]) if n else '65535' for n in enc))
    w('};')
for i, f in enumerate(FONTS):
    wd = fd.widthsByFontGlyph[f]
    w('static const short w14_%d[] = {' % i + ','.join(str(wd.get(n, -1)) for n in names) + '};')
w('const short *const pn_base14_widths[14] = {' + ','.join('w14_%d' % i for i in range(14)) + '};')
w('const char *const pn_base14_names[14] = {' + ','.join(f'"{f}"' for f in FONTS) + '};')
# Ascent/descent
ad = []
for f in FONTS:
    a, d = fd.ascent_descent[f]
    ad.append(f'{{{a},{d}}}')
w('const short pn_base14_ascdesc[14][2] = {' + ','.join(ad) + '};')
# AGL (names outside the encoding set)
extra = sorted((n, u) for n, u in agl.AGL2UV.items() if n not in idx)
w(f'const int pn_agl_count = {len(extra)};')
w('const char *const pn_agl_names[] = {' + ','.join(f'"{n}"' for n, _ in extra) + '};')
w('const unsigned int pn_agl_unicode[] = {' + ','.join(str(u) for _, u in extra) + '};')
print('\n'.join(out))
